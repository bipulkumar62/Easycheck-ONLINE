import 'package:cloud_firestore/cloud_firestore.dart';

/// Queue session model representing the current day's queue for a clinic.
/// Document ID is composite: {clinicId}_{date} where date is YYYY-MM-DD.
class QueueSessionModel {
  final String clinicId;
  final String date; // YYYY-MM-DD
  final int currentParchaNumber;
  final String status; // 'active', 'paused', 'closed'
  final DateTime createdAt;
  final DateTime updatedAt;

  const QueueSessionModel({
    required this.clinicId,
    required this.date,
    required this.currentParchaNumber,
    required this.status,
    required this.createdAt,
    required this.updatedAt,
  });

  /// Create from Firestore document snapshot.
  factory QueueSessionModel.fromDocument(
    Map<String, dynamic> data,
    String documentId,
  ) {
    final parts = documentId.split('_');
    return QueueSessionModel(
      clinicId: parts.first,
      date: parts.skip(1).join('_'),
      currentParchaNumber: data['currentParchaNumber'] as int? ?? 0,
      status: data['status'] as String? ?? 'active',
      createdAt: (data['createdAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
      updatedAt: (data['updatedAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
    );
  }

  /// Convert to Firestore map.
  Map<String, dynamic> toMap() {
    return {
      'clinicId': clinicId,
      'date': date,
      'currentParchaNumber': currentParchaNumber,
      'status': status,
      'createdAt': createdAt,
      'updatedAt': updatedAt,
    };
  }

  /// Valid statuses for a queue session.
  static const List<String> validStatuses = ['active', 'paused', 'closed'];

  QueueSessionModel copyWith({
    int? currentParchaNumber,
    String? status,
    DateTime? updatedAt,
  }) {
    return QueueSessionModel(
      clinicId: clinicId,
      date: date,
      currentParchaNumber: currentParchaNumber ?? this.currentParchaNumber,
      status: status ?? this.status,
      createdAt: createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
    );
  }

  @override
  String toString() {
    return 'QueueSessionModel(clinicId: $clinicId, date: $date, currentParchaNumber: $currentParchaNumber, status: $status)';
  }
}

/// Queue history entry for audit trail.
/// Document ID is auto-generated by Firestore.
class QueueHistoryEntry {
  final String id;
  final String clinicId;
  final String sessionDate;
  final int previousNumber;
  final int newNumber;
  final String action; // 'increment', 'reset', 'correction'
  final String performedBy; // UID of staff member
  final DateTime timestamp;

  const QueueHistoryEntry({
    required this.id,
    required this.clinicId,
    required this.sessionDate,
    required this.previousNumber,
    required this.newNumber,
    required this.action,
    required this.performedBy,
    required this.timestamp,
  });

  /// Create from Firestore document snapshot.
  factory QueueHistoryEntry.fromDocument(Map<String, dynamic> data, String id) {
    return QueueHistoryEntry(
      id: id,
      clinicId: data['clinicId'] as String? ?? '',
      sessionDate: data['sessionDate'] as String? ?? '',
      previousNumber: data['previousNumber'] as int? ?? 0,
      newNumber: data['newNumber'] as int? ?? 0,
      action: data['action'] as String? ?? '',
      performedBy: data['performedBy'] as String? ?? '',
      timestamp: (data['timestamp'] as Timestamp?)?.toDate() ?? DateTime.now(),
    );
  }

  /// Convert to Firestore map.
  Map<String, dynamic> toMap() {
    return {
      'clinicId': clinicId,
      'sessionDate': sessionDate,
      'previousNumber': previousNumber,
      'newNumber': newNumber,
      'action': action,
      'performedBy': performedBy,
      'timestamp': timestamp,
    };
  }

  /// Valid action types.
  static const List<String> validActions = ['increment', 'reset', 'correction'];

  @override
  String toString() {
    return 'QueueHistoryEntry(clinicId: $clinicId, action: $action, previousNumber: $previousNumber, newNumber: $newNumber)';
  }
}
